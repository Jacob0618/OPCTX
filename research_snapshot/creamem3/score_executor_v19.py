"""Score-airgapped Gemini 3.5 judge executor for MemEye matrix v19.

Gold answers and the three historical 0.4533 calibration prediction sets are
opened only after all ten score-free prediction cells have been validated and
sealed.  The first score invocation is provider-free: it computes an exact
unique-triple budget and waits for an independent budget gate.  A later gated
invocation judges only ``question``, ``ground_truth``, and ``model_output``;
legacy verdicts, scores, and reasoning never enter a model-visible request.
"""

