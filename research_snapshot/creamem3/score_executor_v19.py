import hashlib
import importlib
import json
import math
import os
from collections import defaultdict
from pathlib import Path
from typing import Any, Mapping, Protocol, Sequence

from creamem3 import run_memeye_full_arch_matrix_v19 as matrix


SCORE_EXECUTOR_SCHEMA = "creamem3.memeye_full_arch_score_executor.v19.0"
SCORE_BUDGET_SCHEMA = "creamem3.memeye_score_budget.v19.0"
SCORE_BUDGET_GATE_SCHEMA = "creamem3.memeye_score_budget_gate.v19.0"
SCORE_CELL_SCHEMA = "creamem3.memeye_score_cell.v19.0"
SCORE_COMPLETE_SCHEMA = "creamem3.memeye_score_complete.v19.0"
CALIBRATION_SCHEMA = "creamem3.memeye_04533_g35_calibration.v19.0"
MAX_PROVIDER_ATTEMPTS = 3
JUDGE_CACHE_SCOPE = "full_matrix_and_04533_exact_triple_dedupe"

# The base manifest's a09b/1a7b projection labels were not generated by an
# executable canonicalization and therefore cannot gate a formal run.  These
# digests are independently reproducible from sorted unique exact triples.
CALIBRATION_UNIQUE_SORTED_SHA256 = {
    "run1": "829e0723f5f9363f3765be5d7540470f8b797e5a2d6d97c5352336649d896f2e",
    "run2": "90be643456bb07f7b1e668e093b58bb639bfe3f13f83071ad91c284d456399d8",
    "run3": "90be643456bb07f7b1e668e093b58bb639bfe3f13f83071ad91c284d456399d8",
}


class ScoreExecutorError(RuntimeError):
    """Score airgap, source, judge, or receipt failure."""


class JudgeBackend(Protocol):
    def judge(
        self,
        question: str,
        ground_truth: str,
        model_output: str,
        *,
        cache_metadata: Mapping[str, Any] | None = None,
    ) -> tuple[Any, Any]: ...

    def usage_receipt(self) -> Mapping[str, Any]: ...


def _canonical_bytes(value: Any) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")


def _sha256(value: Any) -> str:
    if isinstance(value, bytes):
        payload = value
    elif isinstance(value, str):
        payload = value.encode("utf-8")
    else:
        payload = _canonical_bytes(value)
    return hashlib.sha256(payload).hexdigest()


def _file_sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _read_mapping(path: Path, label: str) -> dict[str, Any]:
    try:
        value = json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception as exc:
        raise ScoreExecutorError(f"invalid {label}: {path}") from exc
    if not isinstance(value, dict):
        raise ScoreExecutorError(f"{label} is not an object: {path}")
    return value


def _write_once(path: Path, value: Mapping[str, Any]) -> None:
    path = Path(path)
    encoded = json.dumps(
        dict(value), ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False
    ) + "\n"
    if path.exists():
        if path.read_text(encoding="utf-8") != encoded:
            raise ScoreExecutorError(f"write-once score artifact drift: {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(encoded)
            handle.flush()
            os.fsync(handle.fileno())
    except Exception:
        path.unlink(missing_ok=True)
        raise


def _mean(values: Sequence[float]) -> float:
    if not values:
        raise ScoreExecutorError("cannot calculate an empty score mean")
    return sum(values) / len(values)


def _durable_gemini_usage(
    receipt: Mapping[str, Any], *, cache_root: Path
) -> dict[str, Any]:
    value = json.loads(json.dumps(dict(receipt), ensure_ascii=False))
    stages = value.get("stages")
    if not isinstance(stages, Mapping):
        raise ScoreExecutorError("G35 usage stages are missing")
    for stage, raw_row in list(stages.items()):
        row = dict(raw_row)
        durable = len(
            list(
                (Path(cache_root) / "attempts" / str(stage)).rglob(
                    "attempt_*_request.json"
                )
            )
        )
        in_process = int(row.get("provider_calls", 0))
        limits = row.get("limits", {})
        row["in_process_provider_calls"] = in_process
        row["durable_provider_attempt_intents"] = durable
        row["provider_calls"] = durable
        row["remaining_live_calls"] = int(limits.get("max_live_calls", 0)) - durable
        stages[stage] = row
    return value


def validate_score_authorities(protocol: Mapping[str, Any]) -> dict[str, Any]:
    authorities = protocol["authority_files"]
    rows: dict[str, Any] = {}
    for name in ("historical_eval_memeye", "g35_runtime"):
        item = authorities[name]
        path = matrix._resolve_authority_path(str(item["path"]))
        actual = _file_sha256(path)
        if actual != item["sha256"]:
            raise ScoreExecutorError(f"score authority drift: {name}")
        rows[name] = {"path": str(path), "sha256": actual}
    receipt = matrix.authority_receipt(protocol)
    if receipt.get("status") != "pass":
        raise ScoreExecutorError("base prompt authority receipt failed")
    judge = protocol["judge_protocol"]
    if (
        receipt["literals"]["judge"]["value_sha256"] != judge["prompt_sha256"]
        or receipt["functions"]["judge_parser"]["source_sha256"]
        != "b46f6e86838a2fea4027ef230dd93455d8c1b896d7d408ab41e17a7df90e480b"
        or receipt["functions"]["judge_mapping"]["source_sha256"]
        != "df3222baf564b0c6d05a79383e075ea5ebcf5b09f3beddc16b77887251550e2c"
    ):
        raise ScoreExecutorError("judge prompt/parser/mapping authority drift")
    return {"status": "pass", "rows": rows, "rows_sha256": _sha256(rows)}


def _strict_prediction_complete(
    output_root: Path, protocol: Mapping[str, Any]
) -> tuple[Any, dict[str, Any]]:
    """Hash-gate the formal predictor before using its strict seal validator."""

    source_path = Path(__file__).with_name("predict_executor_v19.py").resolve()
    raw_complete = _read_mapping(
        Path(output_root) / "predict" / "complete.json", "prediction completion"
    )
    actual_sha = _file_sha256(source_path)
    if raw_complete.get("predict_executor_file_sha256") != actual_sha:
        raise ScoreExecutorError("prediction executor authority/seal drift")
    predictor = importlib.import_module("creamem3.predict_executor_v19")
    if Path(predictor.__file__).resolve() != source_path or _file_sha256(
        Path(predictor.__file__).resolve()
    ) != actual_sha:
        raise ScoreExecutorError("prediction executor import authority drift")
    try:
        completion = predictor._prediction_complete(
            Path(output_root),
            expected_rows=matrix.EXPECTED_QUESTIONS,
            protocol=protocol,
        )
    except Exception as exc:
        raise ScoreExecutorError("strict prediction completion validation failed") from exc
    return predictor, completion


def _prediction_rows(
    output_root: Path, protocol: Mapping[str, Any] | None = None
) -> dict[str, list[dict[str, Any]]]:
    protocol = dict(protocol or matrix.load_protocol())
    _, completion = _strict_prediction_complete(output_root, protocol)
    output: dict[str, list[dict[str, Any]]] = {}
    for cell in completion["cells"]:
        path = Path(str(cell["prediction_path"]))
        value = _read_mapping(path, "prediction cell")
        copy_value = dict(value)
        observed = copy_value.pop("cell_sha256", None)
        rows = value.get("rows")
        if (
            observed != _sha256(copy_value)
            or value.get("schema_version")
            != "creamem3.memeye_prediction_cell.v19.0"
            or value.get("complete") is not True
            or not isinstance(rows, list)
            or len(rows) != matrix.EXPECTED_QUESTIONS
            or value.get("rows_sha256") != _sha256(rows)
        ):
            raise ScoreExecutorError("prediction cell internal seal drift")
        seen: set[str] = set()
        clean: list[dict[str, Any]] = []
        for row in rows:
            if not isinstance(row, Mapping):
                raise ScoreExecutorError("prediction row is not an object")
            keys = {str(key).casefold() for key in row}
            if keys & matrix.FORBIDDEN_PREDICTION_KEYS:
                raise ScoreExecutorError("score-bearing field entered prediction row")
            row_id = str(row.get("row_id", ""))
            prediction = str(row.get("prediction", ""))
            if (
                not row_id
                or row_id in seen
                or not prediction.strip()
                or row.get("prediction_sha256") != _sha256(prediction)
            ):
                raise ScoreExecutorError("prediction row identity/content drift")
            seen.add(row_id)
            clean.append(dict(row))
        output[str(cell["cell_id"])] = clean
    if set(output) != set(matrix.matrix_cell_ids()):
        raise ScoreExecutorError("prediction matrix cell census drift")
    return output


def _gold_rows(
    *,
    output_root: Path,
    score_data_root: Path,
    protocol: Mapping[str, Any] | None = None,
) -> dict[str, tuple[str, str]]:
    """Open only question/answer after prediction completion is sealed."""

    protocol = dict(protocol or matrix.load_protocol())
    _strict_prediction_complete(output_root, protocol)
    project = matrix.validate_project(output_root=output_root)
    if Path(score_data_root).resolve() != matrix.DEFAULT_DATA_ROOT.resolve():
        raise ScoreExecutorError("score data root escaped the frozen dataset")
    task_receipts = {
        str(row["task"]): row for row in project["task_receipts"]
    }
    output: dict[str, tuple[str, str]] = {}
    for task_file in matrix._task_files(Path(score_data_root)):
        task = task_file.stem.removesuffix("_Open")
        receipt = task_receipts.get(task)
        if receipt is None or _file_sha256(task_file) != receipt["source_file_sha256"]:
            raise ScoreExecutorError("raw score source file hash drift")
        value = _read_mapping(task_file, "raw score source")
        qas = value.get("human-annotated QAs")
        if not isinstance(qas, list):
            raise ScoreExecutorError("raw score source lacks QA rows")
        for ordinal, qa in enumerate(qas, start=1):
            if not isinstance(qa, Mapping):
                raise ScoreExecutorError("raw QA row is invalid")
            qid = str(qa.get("question_id", f"Q{ordinal}"))
            row_id = f"{task}::{qid}"
            question = str(qa.get("question", "")).strip()
            gold = str(qa.get("answer", "")).strip()
            if not question or not gold or row_id in output:
                raise ScoreExecutorError("raw gold row identity/content drift")
            output[row_id] = (question, gold)
    if len(output) != matrix.EXPECTED_QUESTIONS:
        raise ScoreExecutorError("raw gold row census drift")
    return output


def _calibration_sources(
    protocol: Mapping[str, Any],
) -> tuple[dict[str, list[tuple[str, str, str]]], dict[str, Any]]:
    config = protocol["historical_04533_g35_rejudge_calibration"]
    output: dict[str, list[tuple[str, str, str]]] = {}
    receipts: dict[str, Any] = {}
    for source in config["sources"]:
        run = str(source["run"])
        path = Path(str(source["path"])).resolve()
        if _file_sha256(path) != source["file_sha256"]:
            raise ScoreExecutorError(f"calibration source hash drift: {run}")
        value = _read_mapping(path, f"calibration {run}")
        raw_rows = value.get("rows")
        if not isinstance(raw_rows, list) or len(raw_rows) != 371:
            raise ScoreExecutorError(f"calibration row census drift: {run}")
        triples = [
            (str(row["question"]), str(row["gold"]), str(row["pred"]))
            for row in raw_rows
            if isinstance(row, Mapping)
        ]
        if len(triples) != 371:
            raise ScoreExecutorError(f"calibration triple projection drift: {run}")
        unique_sorted = sorted(set(triples))
        digest = _sha256([list(item) for item in unique_sorted])
        if (
            len(unique_sorted) != 369
            or digest != CALIBRATION_UNIQUE_SORTED_SHA256[run]
        ):
            raise ScoreExecutorError(
                f"calibration executable unique projection drift: {run}"
            )
        output[run] = triples
        receipts[run] = {
            "path": str(path),
            "file_sha256": source["file_sha256"],
            "rows": len(triples),
            "unique_exact_triples": len(unique_sorted),
            "unique_sorted_exact_triples_sha256": digest,
            "legacy_manifest_projection_sha256": source.get("projection_sha256"),
            "legacy_manifest_projection_gate_eligible": False,
        }
    union = set().union(*(set(rows) for rows in output.values()))
    if len(union) != 566:
        raise ScoreExecutorError("calibration union exact-triple census drift")
    return output, {
        "sources": receipts,
        "union_unique_exact_triples": len(union),
        "union_unique_sorted_exact_triples_sha256": _sha256(
            [list(item) for item in sorted(union)]
        ),
    }


def compute_score_budget(
    *,
    output_root: Path,
    score_data_root: Path,
    protocol: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Open the score airgap but make zero provider calls."""

    protocol = dict(protocol or matrix.load_protocol())
    validate_score_authorities(protocol)
    predictions = _prediction_rows(output_root, protocol)
    gold = _gold_rows(
        output_root=output_root,
        score_data_root=score_data_root,
        protocol=protocol,
    )
    matrix_triples: set[tuple[str, str, str]] = set()
    for rows in predictions.values():
        for row in rows:
            row_id = str(row["row_id"])
            question, answer = gold[row_id]
            if str(row["question"]) != question:
                raise ScoreExecutorError("prediction/raw question mismatch")
            matrix_triples.add((question, answer, str(row["prediction"])))
    calibration, calibration_receipt = _calibration_sources(protocol)
    calibration_union = set().union(*(set(rows) for rows in calibration.values()))
    total_union = matrix_triples | calibration_union
    first = {
        "matrix_unique_exact_triples": len(matrix_triples),
        "calibration_unique_exact_triples": len(calibration_union),
        "cross_scope_duplicate_triples": len(matrix_triples & calibration_union),
        "total_unique_judge_requests": len(total_union),
    }
    value = {
        "schema_version": SCORE_BUDGET_SCHEMA,
        "protocol_sha256": _sha256(protocol),
        "prediction_complete_file_sha256": _file_sha256(
            Path(output_root) / "predict" / "complete.json"
        ),
        "matrix_cells": len(predictions),
        "rows_per_cell": matrix.EXPECTED_QUESTIONS,
        "matrix_rows": sum(len(rows) for rows in predictions.values()),
        "dedupe_key": ["question", "ground_truth", "model_output"],
        "first_attempt_census": first,
        "judge_provider_attempt_hard_ceiling": len(total_union)
        * MAX_PROVIDER_ATTEMPTS,
        "max_provider_attempts": MAX_PROVIDER_ATTEMPTS,
        "calibration_receipt": calibration_receipt,
        "gold_or_prediction_text_persisted": False,
        "matrix_triple_digests_sha256": _sha256(
            sorted(_sha256(list(item)) for item in matrix_triples)
        ),
        "calibration_triple_digests_sha256": _sha256(
            sorted(_sha256(list(item)) for item in calibration_union)
        ),
        "provider_calls": 0,
    }
    value["score_budget_sha256"] = _sha256(value)
    return value


def seal_score_budget(
    *,
    output_root: Path = matrix.DEFAULT_ROOT,
    score_data_root: Path = matrix.DEFAULT_DATA_ROOT,
) -> dict[str, Any]:
    value = compute_score_budget(
        output_root=output_root, score_data_root=score_data_root
    )
    _write_once(Path(output_root) / "score" / "budget.json", value)
    return value


def validate_score_budget_gate(
    *,
    output_root: Path,
    score_data_root: Path,
    protocol: Mapping[str, Any],
) -> dict[str, Any]:
    budget_path = Path(output_root) / "score" / "budget.json"
    gate_path = Path(output_root) / "score" / "budget_gate.json"
    budget = compute_score_budget(
        output_root=output_root,
        score_data_root=score_data_root,
        protocol=protocol,
    )
    if _read_mapping(budget_path, "score budget") != budget:
        raise ScoreExecutorError("score budget file drift")
    gate = _read_mapping(gate_path, "score budget gate")
    copy_gate = dict(gate)
    observed = copy_gate.pop("gate_sha256", None)
    expected = {
        "schema_version": SCORE_BUDGET_GATE_SCHEMA,
        "decision": "approve",
        "reviewer_role": "independent_protocol_auditor",
        "protocol_sha256": _sha256(protocol),
        "budget_path": str(budget_path.resolve()),
        "budget_file_sha256": _file_sha256(budget_path),
        "score_budget_sha256": budget["score_budget_sha256"],
        "approved_judge_provider_attempt_hard_ceiling": budget[
            "judge_provider_attempt_hard_ceiling"
        ],
        "legacy_judge_cache_readthrough": False,
    }
    if observed != _sha256(copy_gate):
        raise ScoreExecutorError("score budget gate self-hash drift")
    for key, value in expected.items():
        if gate.get(key) != value:
            raise ScoreExecutorError(f"score budget gate binding drift: {key}")
    if not str(gate.get("reviewer", "")).strip():
        raise ScoreExecutorError("score budget gate lacks reviewer")
    return {**gate, "budget": budget, "file_sha256": _file_sha256(gate_path)}


def _judge_one(
    judge_backend: JudgeBackend,
    triple: tuple[str, str, str],
    *,
    scope: str,
    triple_sha256: str,
) -> dict[str, Any]:
    question, gold, prediction = triple
    result, verdict = judge_backend.judge(
        question,
        gold,
        prediction,
        cache_metadata={
            "scope": JUDGE_CACHE_SCOPE,
            "exact_triple_sha256": triple_sha256,
        },
    )
    text = str(getattr(result, "text", ""))
    request_sha = str(getattr(result, "request_sha256", ""))
    response_sha = str(getattr(result, "response_sha256", ""))
    raw = float(getattr(verdict, "raw_score"))
    mapped = float(getattr(verdict, "mapped_score"))
    reasoning = str(getattr(verdict, "reasoning", ""))
    if (
        not request_sha
        or response_sha != _sha256(text)
        or raw not in {0.0, 0.25, 0.5, 0.75, 1.0}
        or mapped
        != (0.0 if raw < 0.25 else (0.5 if raw < 0.75 else 1.0))
    ):
        raise ScoreExecutorError("G35 judge reply/parser/mapping drift")
    evidence = _validate_runtime_judge_evidence(
        judge_backend=judge_backend,
        result=result,
        triple=triple,
        scope=JUDGE_CACHE_SCOPE,
        triple_sha256=triple_sha256,
    )
    return {
        "raw_score": raw,
        "mapped_score": mapped,
        "reasoning": reasoning,
        "reasoning_sha256": _sha256(reasoning),
        "request_sha256": request_sha,
        "response_sha256": response_sha,
        **evidence,
    }


def _prefetch_judgements(
    judge_backend: JudgeBackend,
    ordered_triples: Sequence[tuple[tuple[str, str, str], str]],
    *,
    max_workers: int,
) -> dict[tuple[str, str, str], dict[str, Any]]:
    """Judge unique triples concurrently and preserve first-seen ordering.

    ``ordered_triples`` may contain duplicates.  The first occurrence wins,
    matching the previous matrix-then-calibration traversal exactly.  Cache
    metadata and model-visible judge requests are still created by
    :func:`_judge_one` without modification.
    """

    workers = int(max_workers)
    if workers < 1:
        raise ScoreExecutorError("score max_workers must be positive")
    unique: list[tuple[tuple[str, str, str], str]] = []
    seen: set[tuple[str, str, str]] = set()
    for triple, scope in ordered_triples:
        if triple not in seen:
            seen.add(triple)
            unique.append((triple, scope))

    def judge_item(
        item: tuple[tuple[str, str, str], str]
    ) -> tuple[tuple[str, str, str], dict[str, Any]]:
        triple, scope = item
        return (
            triple,
            _judge_one(
                judge_backend,
                triple,
                scope=scope,
                triple_sha256=_sha256(list(triple)),
            ),
        )

    if workers == 1:
        pairs = [judge_item(item) for item in unique]
    else:
        with concurrent.futures.ThreadPoolExecutor(
            max_workers=workers, thread_name_prefix="memeye-score"
        ) as pool:
            pairs = list(pool.map(judge_item, unique))
    return dict(pairs)


def _validate_runtime_judge_evidence(
    *,
    judge_backend: Any,
    result: Any | None,
    triple: tuple[str, str, str],
    scope: str,
    triple_sha256: str,
) -> dict[str, Any]:
    """Reconstruct and validate the complete durable G35 judge cache chain."""

    runtime = importlib.import_module("creamem3.memeye_g35_runtime_v19")
    if not hasattr(judge_backend, "stage_limits"):
        raise ScoreExecutorError("judge backend lacks frozen stage limits")
    question, gold, prediction = triple
    prompt = runtime.build_mgtm_judge_prompt(question, gold, prediction)
    request = runtime.build_generate_content_request(
        "judge",
        prompt,
        json_mode=True,
        max_output_tokens=400,
        stage_limits=judge_backend.stage_limits,
    )
    metadata = {"scope": scope, "exact_triple_sha256": triple_sha256}
    request_sha = runtime.request_identity(
        stage="judge",
        request=request,
        stage_limits=judge_backend.stage_limits,
        cache_metadata=metadata,
    )
    resumable = runtime.resume_hash(
        stage="judge",
        request_sha256=request_sha,
        stage_limits=judge_backend.stage_limits,
    )
    expected_cache_path = (
        Path(judge_backend.cache_root) / "responses" / "judge" / f"{resumable}.json"
    ).resolve()
    cache_path = (
        Path(str(getattr(result, "cache_path", ""))).resolve()
        if result is not None
        else expected_cache_path
    )
    if (
        cache_path != expected_cache_path
        or (
            result is not None
            and (
                request_sha != getattr(result, "request_sha256", None)
                or resumable != getattr(result, "resume_hash", None)
            )
        )
    ):
        raise ScoreExecutorError("judge request/cache identity drift")
    final = _read_mapping(cache_path, "judge final cache")
    final_keys = {
        "schema_version",
        "protocol_sha256",
        "stage",
        "model",
        "request_sha256",
        "resume_hash",
        "attempt_ordinal",
        "response_sha256",
        "text",
        "usage",
        "cache_path",
    }
    if (
        set(final) != final_keys
        or final.get("request_sha256") != request_sha
        or final.get("resume_hash") != resumable
        or final.get("response_sha256") != _sha256(final.get("text", ""))
        or (
            result is not None
            and final.get("response_sha256")
            != getattr(result, "response_sha256", None)
        )
        or (result is not None and final.get("text") != getattr(result, "text", None))
        or Path(str(final.get("cache_path", ""))).resolve() != cache_path
    ):
        raise ScoreExecutorError("judge final cache binding drift")
    ordinal = final.get("attempt_ordinal")
    if not isinstance(ordinal, int) or not 1 <= ordinal <= MAX_PROVIDER_ATTEMPTS:
        raise ScoreExecutorError("judge successful attempt ordinal drift")
    plan_path = Path(judge_backend.cache_root) / "plans" / "judge" / f"{resumable}.json"
    plan = _read_mapping(plan_path, "judge request plan")
    expected_plan = judge_backend._plan_record(
        stage="judge",
        request=request,
        prompt=prompt,
        request_sha=request_sha,
        resumable=resumable,
        caption_context_count=None,
        cache_metadata=metadata,
    )
    if plan != expected_plan:
        raise ScoreExecutorError("judge plan reconstruction drift")
    attempt_request_path, attempt_response_path = judge_backend._attempt_paths(
        "judge", resumable, ordinal
    )
    attempt_request = _read_mapping(attempt_request_path, "judge attempt intent")
    expected_attempt_request = judge_backend._attempt_request_record(
        stage="judge",
        request_sha=request_sha,
        resumable=resumable,
        ordinal=ordinal,
        plan=plan,
    )
    attempt_response = _read_mapping(attempt_response_path, "judge raw response")
    success_response_keys = {
        "schema_version",
        "protocol_sha256",
        "stage",
        "model",
        "request_sha256",
        "resume_hash",
        "attempt_ordinal",
        "attempt_identity_sha256",
        "outcome_kind",
        "response_sha256",
        "text",
        "usage",
    }
    if (
        attempt_request != expected_attempt_request
        or set(attempt_response) != success_response_keys
        or attempt_response.get("attempt_identity_sha256")
        != attempt_request["attempt_identity_sha256"]
        or attempt_response.get("outcome_kind") != "raw_response"
        or attempt_response.get("response_sha256")
        != _sha256(attempt_response.get("text", ""))
        or attempt_response.get("response_sha256") != final["response_sha256"]
        or attempt_response.get("text") != final["text"]
        or attempt_response.get("usage") != final["usage"]
    ):
        raise ScoreExecutorError("judge successful raw response binding drift")
    retry_chain: list[dict[str, Any]] = []
    for previous in range(1, ordinal):
        previous_request_path, previous_response_path = judge_backend._attempt_paths(
            "judge", resumable, previous
        )
        previous_request = _read_mapping(
            previous_request_path, "judge previous attempt intent"
        )
        expected_previous_request = judge_backend._attempt_request_record(
            stage="judge",
            request_sha=request_sha,
            resumable=resumable,
            ordinal=previous,
            plan=plan,
        )
        previous_response = _read_mapping(
            previous_response_path, "judge previous explicit response"
        )
        if (
            previous_request != expected_previous_request
            or previous_response.get("outcome_kind") != "explicit_provider_error"
            or previous_response.get("retryable") is not True
            or previous_response.get("attempt_identity_sha256")
            != previous_request["attempt_identity_sha256"]
        ):
            raise ScoreExecutorError("judge explicit retry chain drift")
        retry_chain.append(
            {
                "ordinal": previous,
                "intent_file_sha256": _file_sha256(previous_request_path),
                "response_file_sha256": _file_sha256(previous_response_path),
                "status_code": previous_response.get("status_code"),
            }
        )
    for later in range(ordinal + 1, MAX_PROVIDER_ATTEMPTS + 1):
        later_request_path, later_response_path = judge_backend._attempt_paths(
            "judge", resumable, later
        )
        if later_request_path.exists() or later_response_path.exists():
            raise ScoreExecutorError("judge post-success attempt drift")
    if judge_backend._orphan_path("judge", resumable).exists() or judge_backend._failure_path(
        "judge", resumable
    ).exists():
        raise ScoreExecutorError("judge success conflicts with terminal receipt")
    return {
        "resume_hash": resumable,
        "successful_attempt_ordinal": ordinal,
        "cache_path": str(cache_path),
        "cache_file_sha256": _file_sha256(cache_path),
        "plan_file_sha256": _file_sha256(plan_path),
        "attempt_request_file_sha256": _file_sha256(attempt_request_path),
        "attempt_response_file_sha256": _file_sha256(attempt_response_path),
        "explicit_retry_chain": retry_chain,
    }


def _validate_judge_row(
    row: Mapping[str, Any],
    triple: tuple[str, str, str],
    *,
    judge_backend: Any | None = None,
    scope: str | None = None,
) -> None:
    raw = float(row.get("raw_score", math.nan))
    mapped = float(row.get("mapped_score", math.nan))
    reasoning = str(row.get("reasoning", ""))
    expected_mapped = 0.0 if raw < 0.25 else (0.5 if raw < 0.75 else 1.0)
    if (
        row.get("exact_triple_sha256") != _sha256(list(triple))
        or raw not in {0.0, 0.25, 0.5, 0.75, 1.0}
        or mapped != expected_mapped
        or row.get("reasoning_sha256") != _sha256(reasoning)
        or not isinstance(row.get("request_sha256"), str)
        or not all(character in "0123456789abcdef" for character in row["request_sha256"])
        or len(row["request_sha256"]) != 64
        or not isinstance(row.get("response_sha256"), str)
        or not all(character in "0123456789abcdef" for character in row["response_sha256"])
        or len(row["response_sha256"]) != 64
    ):
        raise ScoreExecutorError("sealed judge row binding drift")
    if judge_backend is not None:
        if scope is None:
            raise ScoreExecutorError("judge replay scope is missing")
        triple_sha = _sha256(list(triple))
        evidence = _validate_runtime_judge_evidence(
            judge_backend=judge_backend,
            result=None,
            triple=triple,
            scope=JUDGE_CACHE_SCOPE,
            triple_sha256=triple_sha,
        )
        final = _read_mapping(Path(evidence["cache_path"]), "judge replay final")
        runtime = importlib.import_module("creamem3.memeye_g35_runtime_v19")
        verdict = runtime.parse_mgtm_judge_response(final["text"])
        expected = {
            "raw_score": float(verdict.raw_score),
            "mapped_score": float(verdict.mapped_score),
            "reasoning": str(verdict.reasoning),
            "reasoning_sha256": _sha256(str(verdict.reasoning)),
            "request_sha256": str(final["request_sha256"]),
            "response_sha256": str(final["response_sha256"]),
            **evidence,
        }
        if any(row.get(key) != value for key, value in expected.items()):
            raise ScoreExecutorError("sealed judge row/runtime evidence drift")


def _validate_judge_usage(
    *, output_root: Path, usage: Mapping[str, Any], budget: Mapping[str, Any]
) -> int:
    expected_limits = {
        "caption": {"max_output_tokens": 2400, "max_live_calls": 0, "max_attempts": 3},
        "writer": {"max_output_tokens": 16000, "max_live_calls": 0, "max_attempts": 3},
        "view": {"max_output_tokens": 16384, "max_live_calls": 0, "max_attempts": 3},
        "judge": {
            "max_output_tokens": 400,
            "max_live_calls": budget["judge_provider_attempt_hard_ceiling"],
            "max_attempts": 3,
        },
    }
    if (
        not isinstance(usage, Mapping)
        or set(usage)
        != {
            "schema_version",
            "model",
            "cache_root",
            "allow_model_calls",
            "provider_loaded",
            "provider_factory_calls",
            "stages",
        }
        or usage.get("model") != "gemini-3.5-flash-lite"
        or usage.get("allow_model_calls") is not True
        or Path(str(usage.get("cache_root", ""))).resolve()
        != (Path(output_root) / "provider" / "score" / "g35_judge").resolve()
        or set(usage.get("stages", {})) != set(expected_limits)
        or int(usage.get("provider_factory_calls", -1)) not in {0, 1}
    ):
        raise ScoreExecutorError("G35 judge usage receipt drift")
    judge_calls = 0
    for stage, limits in expected_limits.items():
        row = usage["stages"][stage]
        calls = int(row.get("provider_calls", -1))
        if (
            set(row)
            != {
                "provider_calls",
                "in_process_provider_calls",
                "durable_provider_attempt_intents",
                "cache_hits",
                "usage",
                "limits",
                "remaining_live_calls",
            }
            or row.get("limits") != limits
            or row.get("durable_provider_attempt_intents") != calls
            or not 0 <= int(row.get("in_process_provider_calls", -1)) <= calls
            or calls < 0
        ):
            raise ScoreExecutorError(f"G35 stage usage drift: {stage}")
        if stage == "judge":
            if not budget["first_attempt_census"][
                "total_unique_judge_requests"
            ] <= calls <= limits["max_live_calls"]:
                raise ScoreExecutorError("G35 judge ceiling exceeded")
            judge_calls = calls
        elif calls != 0:
            raise ScoreExecutorError("non-judge G35 stage entered score phase")
    return judge_calls


def _validate_score_complete(
    *, output_root: Path, score_data_root: Path, protocol: Mapping[str, Any]
) -> dict[str, Any]:
    """Recompute every score/calibration seal before accepting resume."""

    output_root = Path(output_root).resolve()
    predictions = _prediction_rows(output_root, protocol)
    gold = _gold_rows(
        output_root=output_root,
        score_data_root=score_data_root,
        protocol=protocol,
    )
    gate = validate_score_budget_gate(
        output_root=output_root,
        score_data_root=score_data_root,
        protocol=protocol,
    )
    budget = gate["budget"]
    validate_score_authorities(protocol)
    runtime = importlib.import_module("creamem3.memeye_g35_runtime_v19")
    audit_limits = {
        "caption": runtime.StageLimits(2400, 0, 3),
        "writer": runtime.StageLimits(16000, 0, 3),
        "view": runtime.StageLimits(16384, 0, 3),
        "judge": runtime.StageLimits(
            400, budget["judge_provider_attempt_hard_ceiling"], 3
        ),
    }
    audit_judge = runtime.Gemini35Runtime(
        output_root / "provider" / "score" / "g35_judge",
        allow_model_calls=False,
        provider_factory=lambda: (_ for _ in ()).throw(
            ScoreExecutorError("provider construction during score validation")
        ),
        stage_limits=audit_limits,
    )
    path = output_root / "score" / "complete.json"
    value = _read_mapping(path, "score completion")
    copy_value = dict(value)
    observed = copy_value.pop("complete_sha256", None)
    expected_complete_keys = {
        "schema_version",
        "complete",
        "protocol_sha256",
        "score_executor_file_sha256",
        "prediction_complete_file_sha256",
        "score_budget_sha256",
        "score_budget_gate_file_sha256",
        "cells",
        "calibration",
        "judge_usage",
        "provider_calls",
        "judge_provider_attempt_hard_ceiling",
        "legacy_judge_cache_readthrough",
        "complete_sha256",
    }
    if (
        set(value) != expected_complete_keys
        or
        observed != _sha256(copy_value)
        or value.get("schema_version") != SCORE_COMPLETE_SCHEMA
        or value.get("complete") is not True
        or value.get("protocol_sha256") != _sha256(protocol)
        or value.get("score_executor_file_sha256")
        != _file_sha256(Path(__file__).resolve())
        or value.get("prediction_complete_file_sha256")
        != _file_sha256(output_root / "predict" / "complete.json")
        or value.get("score_budget_sha256") != budget["score_budget_sha256"]
        or value.get("score_budget_gate_file_sha256") != gate["file_sha256"]
        or value.get("judge_provider_attempt_hard_ceiling")
        != budget["judge_provider_attempt_hard_ceiling"]
        or value.get("legacy_judge_cache_readthrough") is not False
    ):
        raise ScoreExecutorError("score completion binding drift")
    cells = value.get("cells")
    if not isinstance(cells, list) or len(cells) != len(matrix.matrix_cell_ids()):
        raise ScoreExecutorError("score completion cell census drift")
    seen: set[str] = set()
    for receipt in cells:
        if not isinstance(receipt, Mapping):
            raise ScoreExecutorError("score cell receipt is invalid")
        if set(receipt) != {
            "cell_id",
            "backbone",
            "architecture",
            "rows",
            "raw_mean",
            "mapped_mean",
            "score_path",
            "score_file_sha256",
            "cell_score_sha256",
        }:
            raise ScoreExecutorError("score cell receipt fieldset drift")
        cell_id = str(receipt.get("cell_id", ""))
        if cell_id in seen or cell_id not in matrix.matrix_cell_ids():
            raise ScoreExecutorError("score cell receipt identity drift")
        seen.add(cell_id)
        backbone, architecture = cell_id.split("__", 1)
        cell_path = Path(str(receipt.get("score_path", ""))).resolve()
        expected_path = (
            output_root / "score" / "cells" / cell_id / "scores.json"
        ).resolve()
        if (
            cell_path != expected_path
            or receipt.get("backbone") != backbone
            or receipt.get("architecture") != architecture
            or receipt.get("rows") != matrix.EXPECTED_QUESTIONS
            or _file_sha256(cell_path) != receipt.get("score_file_sha256")
        ):
            raise ScoreExecutorError("score cell file seal drift")
        artifact = _read_mapping(cell_path, "score cell")
        artifact_copy = dict(artifact)
        artifact_sha = artifact_copy.pop("cell_score_sha256", None)
        rows = artifact.get("rows")
        if (
            set(artifact)
            != {
                "schema_version",
                "cell_id",
                "rows",
                "rows_sha256",
                "raw_mean",
                "mapped_mean",
                "complete",
                "cell_score_sha256",
            }
            or
            artifact_sha != _sha256(artifact_copy)
            or artifact_sha != receipt.get("cell_score_sha256")
            or artifact.get("schema_version") != SCORE_CELL_SCHEMA
            or artifact.get("cell_id") != cell_id
            or artifact.get("complete") is not True
            or not isinstance(rows, list)
            or len(rows) != matrix.EXPECTED_QUESTIONS
            or artifact.get("rows_sha256") != _sha256(rows)
        ):
            raise ScoreExecutorError("score cell internal seal drift")
        for prediction_row, row in zip(predictions[cell_id], rows, strict=True):
            row_id = str(prediction_row["row_id"])
            question, answer = gold[row_id]
            prediction = str(prediction_row["prediction"])
            triple = (question, answer, prediction)
            if (
                not isinstance(row, Mapping)
                or set(row)
                != {
                    "row_id",
                    "question_sha256",
                    "gold_sha256",
                    "prediction_sha256",
                    "exact_triple_sha256",
                    "raw_score",
                    "mapped_score",
                    "reasoning",
                    "reasoning_sha256",
                    "request_sha256",
                    "response_sha256",
                    "resume_hash",
                    "successful_attempt_ordinal",
                    "cache_path",
                    "cache_file_sha256",
                    "plan_file_sha256",
                    "attempt_request_file_sha256",
                    "attempt_response_file_sha256",
                    "explicit_retry_chain",
                }
                or row.get("row_id") != row_id
                or row.get("question_sha256") != _sha256(question)
                or row.get("gold_sha256") != _sha256(answer)
                or row.get("prediction_sha256") != _sha256(prediction)
            ):
                raise ScoreExecutorError("score/prediction row order drift")
            _validate_judge_row(
                row, triple, judge_backend=audit_judge, scope="matrix"
            )
        raw_mean = _mean([float(row["raw_score"]) for row in rows])
        mapped_mean = _mean([float(row["mapped_score"]) for row in rows])
        if (
            artifact.get("raw_mean") != raw_mean
            or artifact.get("mapped_mean") != mapped_mean
            or receipt.get("raw_mean") != raw_mean
            or receipt.get("mapped_mean") != mapped_mean
        ):
            raise ScoreExecutorError("score cell mean drift")
    if seen != set(matrix.matrix_cell_ids()):
        raise ScoreExecutorError("score completion misses matrix cells")

    calibration_receipt = value.get("calibration", {})
    if not isinstance(calibration_receipt, Mapping) or set(calibration_receipt) != {
        "path",
        "file_sha256",
        "calibration_sha256",
        "matrix_cell",
    }:
        raise ScoreExecutorError("calibration receipt fieldset drift")
    calibration_path = Path(str(calibration_receipt.get("path", ""))).resolve()
    expected_calibration_path = (output_root / "score" / "calibration_04533.json").resolve()
    if (
        calibration_path != expected_calibration_path
        or calibration_receipt.get("matrix_cell") is not False
        or calibration_receipt.get("file_sha256") != _file_sha256(calibration_path)
    ):
        raise ScoreExecutorError("calibration file seal drift")
    calibration_value = _read_mapping(calibration_path, "score calibration")
    calibration_copy = dict(calibration_value)
    calibration_sha = calibration_copy.pop("calibration_sha256", None)
    calibration_sources, source_receipt = _calibration_sources(protocol)
    runs = calibration_value.get("runs")
    if (
        set(calibration_value)
        != {
            "schema_version",
            "matrix_cell",
            "source_receipt",
            "runs",
            "three_run_raw_mean",
            "three_run_mapped_mean",
            "complete",
            "calibration_sha256",
        }
        or
        calibration_sha != _sha256(calibration_copy)
        or calibration_sha != calibration_receipt.get("calibration_sha256")
        or calibration_value.get("schema_version") != CALIBRATION_SCHEMA
        or calibration_value.get("matrix_cell") is not False
        or calibration_value.get("complete") is not True
        or calibration_value.get("source_receipt") != source_receipt
        or not isinstance(runs, list)
        or [row.get("run") for row in runs] != ["run1", "run2", "run3"]
    ):
        raise ScoreExecutorError("calibration internal seal drift")
    for run_value in runs:
        if not isinstance(run_value, Mapping) or set(run_value) != {
            "run",
            "rows",
            "rows_sha256",
            "raw_mean",
            "mapped_mean",
        }:
            raise ScoreExecutorError("calibration run fieldset drift")
        run = str(run_value["run"])
        rows = run_value.get("rows")
        triples = calibration_sources[run]
        if (
            not isinstance(rows, list)
            or len(rows) != len(triples)
            or run_value.get("rows_sha256") != _sha256(rows)
        ):
            raise ScoreExecutorError("calibration run row seal drift")
        for ordinal, (triple, row) in enumerate(zip(triples, rows, strict=True)):
            if (
                not isinstance(row, Mapping)
                or set(row)
                != {
                    "source_ordinal",
                    "exact_triple_sha256",
                    "raw_score",
                    "mapped_score",
                    "reasoning",
                    "reasoning_sha256",
                    "request_sha256",
                    "response_sha256",
                    "resume_hash",
                    "successful_attempt_ordinal",
                    "cache_path",
                    "cache_file_sha256",
                    "plan_file_sha256",
                    "attempt_request_file_sha256",
                    "attempt_response_file_sha256",
                    "explicit_retry_chain",
                }
                or row.get("source_ordinal") != ordinal
            ):
                raise ScoreExecutorError("calibration source order drift")
            _validate_judge_row(
                row,
                triple,
                judge_backend=audit_judge,
                scope="historical_04533_calibration",
            )
        raw_mean = _mean([float(row["raw_score"]) for row in rows])
        mapped_mean = _mean([float(row["mapped_score"]) for row in rows])
        if run_value.get("raw_mean") != raw_mean or run_value.get(
            "mapped_mean"
        ) != mapped_mean:
            raise ScoreExecutorError("calibration run mean drift")
    if calibration_value.get("three_run_raw_mean") != _mean(
        [float(row["raw_mean"]) for row in runs]
    ) or calibration_value.get("three_run_mapped_mean") != _mean(
        [float(row["mapped_mean"]) for row in runs]
    ):
        raise ScoreExecutorError("calibration three-run mean drift")

    judge_calls = _validate_judge_usage(
        output_root=output_root,
        usage=value.get("judge_usage", {}),
        budget=budget,
    )
    if value.get("provider_calls") != judge_calls:
        raise ScoreExecutorError("score provider census binding drift")
    return value


def execute_score_with_backend(
    *,
    output_root: Path,
    score_data_root: Path,
    judge_backend: JudgeBackend,
    budget_gate: Mapping[str, Any],
    max_workers: int = 1,
) -> dict[str, Any]:
    protocol = matrix.load_protocol()
    validate_score_authorities(protocol)
    complete_path = Path(output_root) / "score" / "complete.json"
    if complete_path.is_file():
        value = _validate_score_complete(
            output_root=output_root,
            score_data_root=score_data_root,
            protocol=protocol,
        )
        return {
            "status": "resumed_complete",
            "provider_calls": 0,
            "complete_path": str(complete_path.resolve()),
            "complete_sha256": value["complete_sha256"],
        }
    budget = compute_score_budget(
        output_root=output_root,
        score_data_root=score_data_root,
        protocol=protocol,
    )
    if budget_gate.get("budget") != budget:
        raise ScoreExecutorError("injected score budget gate drift")
    predictions = _prediction_rows(output_root, protocol)
    gold = _gold_rows(
        output_root=output_root,
        score_data_root=score_data_root,
        protocol=protocol,
    )
    workers = int(max_workers)
    if workers < 1:
        raise ScoreExecutorError("score max_workers must be positive")
    calibration: dict[str, list[tuple[str, str, str]]] | None = None
    source_receipt: dict[str, Any] | None = None
    if workers == 1:
        # Retain the formal executor's historical on-demand call/write order.
        result_cache: dict[tuple[str, str, str], dict[str, Any]] = {}
    else:
        calibration, source_receipt = _calibration_sources(protocol)
        ordered_triples: list[tuple[tuple[str, str, str], str]] = []
        for cell_id in matrix.matrix_cell_ids():
            for prediction_row in predictions[cell_id]:
                question, answer = gold[str(prediction_row["row_id"])]
                ordered_triples.append(
                    (
                        (question, answer, str(prediction_row["prediction"])),
                        "matrix",
                    )
                )
        for run in ("run1", "run2", "run3"):
            ordered_triples.extend(
                (triple, "historical_04533_calibration")
                for triple in calibration[run]
            )
        result_cache = _prefetch_judgements(
            judge_backend, ordered_triples, max_workers=workers
        )
    cell_receipts: list[dict[str, Any]] = []
    for cell_id in matrix.matrix_cell_ids():
        rows: list[dict[str, Any]] = []
        for prediction_row in predictions[cell_id]:
            row_id = str(prediction_row["row_id"])
            question, answer = gold[row_id]
            prediction = str(prediction_row["prediction"])
            triple = (question, answer, prediction)
            triple_sha = _sha256(list(triple))
            if triple not in result_cache:
                result_cache[triple] = _judge_one(
                    judge_backend, triple, scope="matrix", triple_sha256=triple_sha
                )
            verdict = result_cache[triple]
            rows.append(
                {
                    "row_id": row_id,
                    "question_sha256": _sha256(question),
                    "gold_sha256": _sha256(answer),
                    "prediction_sha256": _sha256(prediction),
                    "exact_triple_sha256": triple_sha,
                    **verdict,
                }
            )
        if len(rows) != matrix.EXPECTED_QUESTIONS:
            raise ScoreExecutorError("score cell row census drift")
        cell_value = {
            "schema_version": SCORE_CELL_SCHEMA,
            "cell_id": cell_id,
            "rows": rows,
            "rows_sha256": _sha256(rows),
            "raw_mean": _mean([row["raw_score"] for row in rows]),
            "mapped_mean": _mean([row["mapped_score"] for row in rows]),
            "complete": True,
        }
        cell_value["cell_score_sha256"] = _sha256(cell_value)
        cell_path = Path(output_root) / "score" / "cells" / cell_id / "scores.json"
        _write_once(cell_path, cell_value)
        cell_receipts.append(
            {
                "cell_id": cell_id,
                "backbone": cell_id.split("__", 1)[0],
                "architecture": cell_id.split("__", 1)[1],
                "rows": len(rows),
                "raw_mean": cell_value["raw_mean"],
                "mapped_mean": cell_value["mapped_mean"],
                "score_path": str(cell_path.resolve()),
                "score_file_sha256": _file_sha256(cell_path),
                "cell_score_sha256": cell_value["cell_score_sha256"],
            }
        )

    if calibration is None or source_receipt is None:
        calibration, source_receipt = _calibration_sources(protocol)
    calibration_runs: list[dict[str, Any]] = []
    for run in ("run1", "run2", "run3"):
        rows: list[dict[str, Any]] = []
        for ordinal, triple in enumerate(calibration[run]):
            triple_sha = _sha256(list(triple))
            if triple not in result_cache:
                result_cache[triple] = _judge_one(
                    judge_backend,
                    triple,
                    scope="historical_04533_calibration",
                    triple_sha256=triple_sha,
                )
            rows.append(
                {
                    "source_ordinal": ordinal,
                    "exact_triple_sha256": triple_sha,
                    **result_cache[triple],
                }
            )
        run_value = {
            "run": run,
            "rows": rows,
            "rows_sha256": _sha256(rows),
            "raw_mean": _mean([row["raw_score"] for row in rows]),
            "mapped_mean": _mean([row["mapped_score"] for row in rows]),
        }
        calibration_runs.append(run_value)
    calibration_value = {
        "schema_version": CALIBRATION_SCHEMA,
        "matrix_cell": False,
        "source_receipt": source_receipt,
        "runs": calibration_runs,
        "three_run_raw_mean": _mean([row["raw_mean"] for row in calibration_runs]),
        "three_run_mapped_mean": _mean(
            [row["mapped_mean"] for row in calibration_runs]
        ),
        "complete": True,
    }
    calibration_value["calibration_sha256"] = _sha256(calibration_value)
    calibration_path = Path(output_root) / "score" / "calibration_04533.json"
    _write_once(calibration_path, calibration_value)

    usage = _durable_gemini_usage(
        judge_backend.usage_receipt(),
        cache_root=Path(output_root) / "provider" / "score" / "g35_judge",
    )
    stages = usage.get("stages", {})
    provider_calls = int(stages.get("judge", {}).get("provider_calls", 0))
    if provider_calls > budget["judge_provider_attempt_hard_ceiling"]:
        raise ScoreExecutorError("score judge provider-attempt ceiling exceeded")
    complete = {
        "schema_version": SCORE_COMPLETE_SCHEMA,
        "complete": True,
        "protocol_sha256": _sha256(protocol),
        "score_executor_file_sha256": _file_sha256(Path(__file__).resolve()),
        "prediction_complete_file_sha256": budget[
            "prediction_complete_file_sha256"
        ],
        "score_budget_sha256": budget["score_budget_sha256"],
        "score_budget_gate_file_sha256": budget_gate.get("file_sha256"),
        "cells": cell_receipts,
        "calibration": {
            "path": str(calibration_path.resolve()),
            "file_sha256": _file_sha256(calibration_path),
            "calibration_sha256": calibration_value["calibration_sha256"],
            "matrix_cell": False,
        },
        "judge_usage": usage,
        "provider_calls": provider_calls,
        "judge_provider_attempt_hard_ceiling": budget[
            "judge_provider_attempt_hard_ceiling"
        ],
        "legacy_judge_cache_readthrough": False,
    }
    complete["complete_sha256"] = _sha256(complete)
    _write_once(complete_path, complete)
    _validate_score_complete(
        output_root=output_root,
        score_data_root=score_data_root,
        protocol=protocol,
    )
    return {
        "status": "complete",
        "provider_calls": provider_calls,
        "complete_path": str(complete_path.resolve()),
        "complete_sha256": complete["complete_sha256"],
        "cells": len(cell_receipts),
        "calibration_runs": 3,
    }


def run_matrix_phase(request: Mapping[str, Any]) -> dict[str, Any]:
    if request.get("phase") != "score":
        raise ScoreExecutorError("score executor accepts only phase=score")
    protocol = matrix.load_protocol(Path(str(request["protocol_path"])))
    output_root = Path(str(request["output_root"])).resolve()
    score_data_root = Path(str(request["score_data_root"])).resolve()
    if (
        request.get("protocol_sha256") != _sha256(protocol)
        or request.get("legacy_cache_readthrough") is not False
        or output_root != matrix.DEFAULT_ROOT.resolve()
    ):
        raise ScoreExecutorError("formal score request contract drift")
    validate_score_authorities(protocol)
    _strict_prediction_complete(output_root, protocol)
    budget_path = output_root / "score" / "budget.json"
    if not budget_path.is_file():
        budget = seal_score_budget(
            output_root=output_root, score_data_root=score_data_root
        )
        return {
            "status": "waiting_score_budget_gate",
            "provider_calls": 0,
            "score_budget_path": str(budget_path.resolve()),
            "score_budget_sha256": budget["score_budget_sha256"],
            "judge_provider_attempt_hard_ceiling": budget[
                "judge_provider_attempt_hard_ceiling"
            ],
        }
    gate = validate_score_budget_gate(
        output_root=output_root,
        score_data_root=score_data_root,
        protocol=protocol,
    )
    # The source was hash-gated above.  Provider construction occurs only
    # after prediction, score budget, independent gate, and main smoke gates.
    runtime = importlib.import_module("creamem3.memeye_g35_runtime_v19")
    limits = {
        "caption": runtime.StageLimits(2400, 0, 3),
        "writer": runtime.StageLimits(16000, 0, 3),
        "view": runtime.StageLimits(16384, 0, 3),
        "judge": runtime.StageLimits(
            400, gate["budget"]["judge_provider_attempt_hard_ceiling"], 3
        ),
    }
    judge = runtime.Gemini35Runtime(
        output_root / "provider" / "score" / "g35_judge",
        allow_model_calls=True,
        stage_limits=limits,
    )
    return execute_score_with_backend(
        output_root=output_root,
        score_data_root=score_data_root,
        judge_backend=judge,
        budget_gate=gate,
    )


